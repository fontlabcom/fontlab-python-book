    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        shutil.copytree(ROOT / "src_docs", self.root / "src_docs")
        self.env = dict(os.environ, SOURCE_DATE_EPOCH="1794528000")

    def build(self, name):
        output = self.root / name
        result = subprocess.run(
            ["sh", "src_docs/build.sh", "--site-dir", str(output)],
            cwd=self.root,
            env=self.env,
            check=False,
            capture_output=True,
            text=True,
            timeout=120,
        )
        return result, output

