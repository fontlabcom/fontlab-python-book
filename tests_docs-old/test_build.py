    def test_missing_navigation_content_fails_strict_build(self):
        config = self.root / "src_docs/mkdocs.yml"
        config.write_text(config.read_text().replace("index.md", "missing.md"))
        result, _ = self.build("missing")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("missing.md", result.stdout + result.stderr)


